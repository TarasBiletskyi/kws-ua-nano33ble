"""Export a LiteRT model file as a C array for the firmware, plus ``model_meta.json``.

    python tools/export_model.py [--tflite firmware/kws_nano33/model/with_aug_two_output_int8.tflite]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path

import numpy as np

from kws_paths import FIRMWARE_DIR, MODEL_DIR, MODEL_REPO, PUBLISHED_MODEL, TWO_OUTPUT_MODEL, load_config


def tensor_info(d: dict) -> dict:
    return {"name": d.get("name", ""), "index": int(d["index"]), "shape": [int(v) for v in d["shape"]],
            "dtype": str(np.dtype(d["dtype"])), "scale": float(d["quantization"][0]), "zero_point": int(d["quantization"][1])}


def model_meta(path: Path, blob: bytes, symbol: str) -> dict:
    from ai_edge_litert import interpreter as lr
    import ai_edge_litert
    it = lr.Interpreter(model_path=str(path), experimental_op_resolver_type=lr.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
    it.allocate_tensors()
    ops = [str(o["op_name"]) for o in it._get_ops_details()]
    cfg = load_config()
    commit = subprocess.run(["git", "-C", str(MODEL_REPO), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    return {
        "file": path.name, "bytes": len(blob), "sha256": hashlib.sha256(blob).hexdigest(), "c_symbol": symbol,
        "inputs": [tensor_info(d) for d in it.get_input_details()],
        "outputs": [tensor_info(d) for d in it.get_output_details()],
        "ops": ops, "n_ops": len(ops), "n_tensors": len(it.get_tensor_details()),
        "classes": list(cfg["classes"]),
        "model_repo_commit": commit, "litert_version": getattr(ai_edge_litert, "__version__", "?"),
    }


def write_c_array(blob: bytes, symbol: str, cpp: Path, header: Path, src_name: str) -> None:
    lines = [f"// GENERATED by tools/export_model.py from {src_name} — do not edit.", f'#include "{header.name}"', "",
             f"alignas(16) const unsigned char {symbol}[] = {{"]
    for i in range(0, len(blob), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in blob[i:i + 12]) + ",")
    lines += ["};", f"const unsigned int {symbol}_len = {len(blob)};", ""]
    cpp.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    header.write_text("\n".join([
        f"// GENERATED by tools/export_model.py from {src_name} — do not edit.", "#pragma once",
        f"extern const unsigned char {symbol}[];", f"extern const unsigned int {symbol}_len;",
        f"#define KWS_MODEL_BYTES {len(blob)}", f'#define KWS_MODEL_SHA256_8 "{hashlib.sha256(blob).hexdigest()[:8]}"', ""]),
        encoding="utf-8", newline="\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    default = TWO_OUTPUT_MODEL if TWO_OUTPUT_MODEL.exists() else PUBLISHED_MODEL
    ap.add_argument("--tflite", type=Path, default=default)
    ap.add_argument("--symbol", default="g_kws_model")
    ap.add_argument("--out-dir", type=Path, default=FIRMWARE_DIR)
    ap.add_argument("--meta", type=Path, default=MODEL_DIR / "model_meta.json")
    args = ap.parse_args()
    blob = args.tflite.read_bytes()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    write_c_array(blob, args.symbol, args.out_dir / "model_data.cpp", args.out_dir / "model_data.h", args.tflite.name)
    meta = model_meta(args.tflite, blob, args.symbol)
    args.meta.parent.mkdir(parents=True, exist_ok=True)
    args.meta.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"{args.tflite.name}: {len(blob)} B, sha256 {meta['sha256'][:16]}…, ops {meta['n_ops']} ({', '.join(sorted(set(meta['ops'])))})")
    for o in meta["outputs"]:
        print(f"  output shape {o['shape']} scale {o['scale']:.8f} zp {o['zero_point']}")
    print(f"written {args.out_dir / 'model_data.cpp'}, {args.out_dir / 'model_data.h'}, {args.meta}")


if __name__ == "__main__":
    main()
