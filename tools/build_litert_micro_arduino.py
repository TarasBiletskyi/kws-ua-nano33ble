"""Turn a tree generated from tensorflow/tflite-micro (LiteRT for Microcontrollers) into the Arduino library ``LiteRT_Micro``.

There is no current Arduino packaging of LiteRT for Microcontrollers: the official ``Arduino_TensorFlowLite`` is an archived
December 2023 snapshot that mishandles the per-class weight scales of models from recent converters. The upstream tool
``create_tflm_tree.py`` outputs the sources; an Arduino library additionally needs these changes, all made here:

  * ``.cc`` becomes ``.cpp``, because the Arduino builder ignores ``.cc``;
  * includes are rewritten to paths relative to ``src``, because a library cannot add ``-I`` flags;
  * ``-D`` flags of the upstream Makefile go into ``litert_micro_config.h``, included first in every file;
  * the generic Cortex-M port (debug log, timer) is replaced by a small Arduino port;
  * ``third_party/cmsis`` is dropped, because the Mbed core has its own CMSIS.

Windows prerequisites and the generation step are in firmware/kws_nano33/README.md. Then:

    python tools/build_litert_micro_arduino.py --tree C:/lb/tree --commit 85c6999a1f0032f64f3b0002431a357b451275c4

The library must be compiled as C++17:
    arduino-cli compile --build-property "compiler.cpp.extra_flags=-std=gnu++17" ...
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

COPY_DIRS = ["tensorflow", "signal", "third_party/flatbuffers", "third_party/kissfft", "third_party/cmsis_nn"]
DROP_FILES = ["tensorflow/lite/micro/cortex_m_generic/debug_log.cc", "tensorflow/lite/micro/cortex_m_generic/micro_time.cc"]
# Directories searched for an include that is not relative to src or to the including file.
INCLUDE_ROOTS = ["third_party/cmsis_nn/Include", "third_party/cmsis_nn", "third_party/flatbuffers/include", "third_party/kissfft"]
TEXT_SUFFIXES = {".h", ".hpp", ".c", ".cc", ".cpp", ".inc"}
SOURCE_OR_HEADER = {".h", ".hpp", ".c", ".cpp"}
INCLUDE_RE = re.compile(r'^(\s*#\s*include\s+")([^"]+)(")', re.M)

CONFIG_H = """// GENERATED by tools/build_litert_micro_arduino.py. The -D flags of the upstream Makefile for
// TARGET=cortex_m_generic TARGET_ARCH=cortex-m4+sfp OPTIMIZED_KERNEL_DIR=cmsis_nn.
#pragma once
#ifndef CMSIS_NN
#define CMSIS_NN
#endif
#ifndef TFLM_REMOVE_VIRTUAL_DELETE
#define TFLM_REMOVE_VIRTUAL_DELETE
#endif
#ifndef TF_LITE_DISABLE_X86_NEON
#define TF_LITE_DISABLE_X86_NEON
#endif
#ifndef FLATBUFFERS_LOCALE_INDEPENDENT
#define FLATBUFFERS_LOCALE_INDEPENDENT 0
#endif
#ifndef FLATBUFFERS_PREFER_PRINTF
#define FLATBUFFERS_PREFER_PRINTF 1
#endif
#ifndef TF_LITE_MCU_DEBUG_LOG
#define TF_LITE_MCU_DEBUG_LOG
#endif
#ifndef CPU_M4
#define CPU_M4 1
#endif
#ifndef ARM_NN_ENABLE_F16
#define ARM_NN_ENABLE_F16 0
#endif
#ifndef ARM_NN_ENABLE_F32
#define ARM_NN_ENABLE_F32 0
#endif

// DSP intrinsics absent from arm_acle.h of GCC 7.2 (core mbed_nano 4.6.0). CMSIS-NN uses them in hot loops, for example
// in arm_depthwise_conv_3x3_s8, so they must be inline: a function call per multiplication costs about 70 % in that kernel.
#if defined(__GNUC__) && !defined(__clang__) && (__GNUC__ < 10) && defined(__ARM_FEATURE_DSP)
#include <stdint.h>
__attribute__((always_inline)) static inline int32_t __sxtb16(int32_t x) {
  int32_t r;
  __asm("sxtb16 %0, %1" : "=r"(r) : "r"(x));
  return r;
}
__attribute__((always_inline)) static inline int32_t __smlabb(int32_t a, int32_t b, int32_t c) {
  int32_t r;
  __asm("smlabb %0, %1, %2, %3" : "=r"(r) : "r"(a), "r"(b), "r"(c));
  return r;
}
__attribute__((always_inline)) static inline int32_t __smlatt(int32_t a, int32_t b, int32_t c) {
  int32_t r;
  __asm("smlatt %0, %1, %2, %3" : "=r"(r) : "r"(a), "r"(b), "r"(c));
  return r;
}
#endif
"""

MAIN_H = """// litert_micro.h: umbrella include of the Arduino library LiteRT_Micro (GENERATED by tools/build_litert_micro_arduino.py).
// Include this first: this include is what makes the Arduino builder find the library.
#pragma once
#include "litert_micro_config.h"
"""

PORT_CPP = """// Arduino port of LiteRT for Microcontrollers (GENERATED by tools/build_litert_micro_arduino.py):
// replaces cortex_m_generic/debug_log.cc and micro_time.cc. Log messages go to Serial, ticks are DWT CPU cycles.
#include "litert_micro_config.h"

#include <Arduino.h>
#include <stdarg.h>
#include <stdio.h>

#include <cmsis.h>

#include "tensorflow/lite/micro/debug_log.h"
#include "tensorflow/lite/micro/micro_time.h"

extern "C" void DebugLog(const char* format, va_list args) {
  char buffer[256];
  vsnprintf(buffer, sizeof(buffer), format, args);
  Serial.print(buffer);
}

extern "C" int DebugVsnprintf(char* buffer, size_t buf_size, const char* format, va_list vlist) {
  return vsnprintf(buffer, buf_size, format, vlist);
}

namespace tflite {
namespace micro {

uint32_t ticks_per_second() { return SystemCoreClock; }

uint32_t GetCurrentTimeTicks() {
  static bool started = false;
  if (!started) {
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
    started = true;
  }
  return DWT->CYCCNT;
}

}  // namespace micro
}  // namespace tflite
"""


def rewrite_includes(text: str, file_rel: Path, src: Path) -> tuple[str, list[str]]:
    unresolved = []

    def fix(m: re.Match) -> str:
        inc = m.group(2)
        if (src / inc).is_file() or (src / file_rel.parent / inc).is_file():
            return m.group(0)
        for root in INCLUDE_ROOTS:
            if (src / root / inc).is_file():
                return f"{m.group(1)}{root}/{inc}{m.group(3)}"
        # The generator flattens kissfft/tools into kissfft.
        if inc.startswith("tools/") and (src / "third_party/kissfft" / inc[len("tools/"):]).is_file():
            return f"{m.group(1)}third_party/kissfft/{inc[len('tools/'):]}{m.group(3)}"
        unresolved.append(inc)
        return m.group(0)

    return INCLUDE_RE.sub(fix, text), unresolved


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tree", type=Path, required=True, help="output directory of create_tflm_tree.py")
    ap.add_argument("--commit", required=True, help="tensorflow/tflite-micro commit the tree was generated from")
    ap.add_argument("--out", type=Path, default=Path.home() / "Documents" / "Arduino" / "libraries" / "LiteRT_Micro")
    args = ap.parse_args()

    out, src = args.out, args.out / "src"
    if out.exists():
        shutil.rmtree(out)
    src.mkdir(parents=True)
    for d in COPY_DIRS:
        shutil.copytree(args.tree / d, src / d)
    for f in DROP_FILES:
        (src / f).unlink()

    # .cc -> .cpp first, so that the include check below sees the final names. Headers keep their names.
    for p in list(src.rglob("*.cc")):
        p.rename(p.with_suffix(".cpp"))
    for p in list(src.rglob("*")):
        if p.is_file() and p.suffix not in TEXT_SUFFIXES and p.name not in ("LICENSE", "LICENSE.txt", "COPYING"):
            p.unlink()

    (src / "litert_micro_config.h").write_text(CONFIG_H, encoding="utf-8", newline="\n")
    (src / "litert_micro.h").write_text(MAIN_H, encoding="utf-8", newline="\n")

    unresolved: dict[str, int] = {}
    files = 0
    for p in src.rglob("*"):
        if not (p.is_file() and p.suffix in TEXT_SUFFIXES) or p.name in ("litert_micro_config.h", "litert_micro.h"):
            continue
        rel = p.relative_to(src)
        text, missing = rewrite_includes(p.read_text(encoding="utf-8", errors="surrogateescape"), rel, src)
        for m in missing:
            unresolved[m] = unresolved.get(m, 0) + 1
        if p.suffix in SOURCE_OR_HEADER:
            text = '#include "litert_micro_config.h"\n' + text
        p.write_text(text, encoding="utf-8", errors="surrogateescape", newline="\n")
        files += 1

    port = src / "tensorflow" / "lite" / "micro" / "arduino" / "litert_micro_port.cpp"
    port.parent.mkdir(parents=True)
    port.write_text(PORT_CPP, encoding="utf-8", newline="\n")

    (out / "library.properties").write_text(
        "name=LiteRT_Micro\n"
        f"version=0.0.0\n"
        "author=The TensorFlow / LiteRT authors\n"
        "maintainer=kws-ua-nano33ble (generated, see tools/build_litert_micro_arduino.py)\n"
        f"sentence=LiteRT for Microcontrollers with CMSIS-NN kernels, tensorflow/tflite-micro commit {args.commit[:9]}.\n"
        "paragraph=Generated for Cortex-M4 with softfp ABI. Compile as C++17.\n"
        "category=Data Processing\n"
        "url=https://github.com/tensorflow/tflite-micro\n"
        "architectures=mbed_nano\n"
        "includes=litert_micro.h\n",
        encoding="utf-8", newline="\n")
    (out / "PROVENANCE.txt").write_text(
        f"tensorflow/tflite-micro commit: {args.commit}\n"
        "create_tflm_tree.py options: TARGET=cortex_m_generic TARGET_ARCH=cortex-m4+sfp OPTIMIZED_KERNEL_DIR=cmsis_nn\n",
        encoding="utf-8", newline="\n")
    if (args.tree / "LICENSE").exists():
        shutil.copy(args.tree / "LICENSE", out / "LICENSE")

    sources = sum(1 for p in src.rglob("*") if p.suffix in (".c", ".cpp"))
    print(f"{out}: {files} files processed, {sources} compile units")
    print("includes left as they are (system headers, or code behind an #ifdef for other targets):")
    for name, n in sorted(unresolved.items()):
        print(f"  {name} ({n})")


if __name__ == "__main__":
    main()
