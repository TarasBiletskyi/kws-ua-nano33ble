"""Golden vectors for device verification (V1/V2): audio → log-mel → features → int8 input → int8 outputs.

Stratified sample of test clips (3 per class + extras from the largest classes), computed with the librosa
reference (``src.features.extract_mfcc``), the table-driven NumPy frontend and the LiteRT runtime on the
two-output model. Writes ``tools/golden/golden_vectors.npz`` + ``golden_index.json`` and the on-board self-test
header ``firmware/kws_nano33/golden_set.h`` (audio for the first few clips, int8 vectors for a few more).

    python tools/export_golden.py [--n 50] [--with-tflite]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import soundfile as sf

from kws_paths import (FIRMWARE_DIR, GOLDEN_DIR, PUBLISHED_MODEL, REPO_ROOT, TWO_OUTPUT_MODEL, add_model_repo_to_path,
                       default_corpus_root, load_config, list_test_clips)
from export_tables import build_tables
from frontend_ref import features, quantize

add_model_repo_to_path()


def select_clips(clips, classes, n, seed):
    rng = np.random.default_rng(seed)
    per_class = {c: [x for x in clips if x[1] == c] for c in classes}
    base = n // len(classes)
    chosen = []
    for c in classes:
        pool = per_class[c]
        k = min(base, len(pool))
        chosen += [pool[i] for i in sorted(rng.choice(len(pool), size=k, replace=False))]
    extra_classes = sorted(classes, key=lambda c: -len(per_class[c]))
    i = 0
    while len(chosen) < n:
        pool = [x for x in per_class[extra_classes[i % len(classes)]] if x not in chosen]
        chosen.append(pool[int(rng.integers(len(pool)))])
        i += 1
    return chosen


def litert(path: Path):
    from ai_edge_litert import interpreter as lr
    it = lr.Interpreter(model_path=str(path), experimental_op_resolver_type=lr.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
    it.allocate_tensors()
    return it


def run_two(it, x_int8):
    inp = it.get_input_details()[0]
    it.set_tensor(inp["index"], x_int8[np.newaxis, :, :, np.newaxis])
    it.invoke()
    outs = {int(o["shape"][-1]): it.get_tensor(o["index"])[0].copy() for o in it.get_output_details()}
    return outs[15], outs.get(64)


def write_header(path: Path, stems, labels, classes, audio, x_int8, prob, gap, n_audio, n_feat) -> None:
    def arr(name, a, ctype, per_line):
        flat = np.asarray(a).ravel()
        body = ",\n".join("  " + ", ".join(str(int(v)) for v in flat[i:i + per_line]) for i in range(0, len(flat), per_line))
        return f"static const {ctype} {name}[{len(flat)}] = {{\n{body}\n}};\n"
    lines = ["// GENERATED by tools/export_golden.py — do not edit. On-board self-test vectors (see tools/golden/).",
             "#pragma once", "#include <stdint.h>", "",
             f"#define GOLDEN_N_AUDIO {n_audio}", f"#define GOLDEN_N_FEAT {n_feat}", ""]
    for i in range(n_feat):
        lines.append(f"// clip {i}: {stems[i]}  class {classes[labels[i]]} (index {labels[i]})")
    lines.append(arr("GOLDEN_LABELS", labels[:n_feat], "uint8_t", 16))
    for i in range(n_audio):
        lines.append(arr(f"GOLDEN_AUDIO_{i}", audio[i], "int16_t", 16))
    for i in range(n_feat):
        lines.append(arr(f"GOLDEN_INPUT_{i}", x_int8[i], "int8_t", 39))
        lines.append(arr(f"GOLDEN_PROB_{i}", prob[i], "int8_t", 15))
        if gap is not None:
            lines.append(arr(f"GOLDEN_GAP_{i}", gap[i], "int8_t", 16))
    lines.append("static const int16_t* const GOLDEN_AUDIO[GOLDEN_N_AUDIO] = { " + ", ".join(f"GOLDEN_AUDIO_{i}" for i in range(n_audio)) + " };")
    lines.append("static const int8_t* const GOLDEN_INPUT[GOLDEN_N_FEAT] = { " + ", ".join(f"GOLDEN_INPUT_{i}" for i in range(n_feat)) + " };")
    lines.append("static const int8_t* const GOLDEN_PROB[GOLDEN_N_FEAT] = { " + ", ".join(f"GOLDEN_PROB_{i}" for i in range(n_feat)) + " };")
    if gap is not None:
        lines.append("static const int8_t* const GOLDEN_GAP[GOLDEN_N_FEAT] = { " + ", ".join(f"GOLDEN_GAP_{i}" for i in range(n_feat)) + " };")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model", type=Path, default=TWO_OUTPUT_MODEL if TWO_OUTPUT_MODEL.exists() else PUBLISHED_MODEL)
    ap.add_argument("--n", type=int, default=50)
    ap.add_argument("--n-header-audio", type=int, default=3)
    ap.add_argument("--n-header-feat", type=int, default=5)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--with-tflite", action="store_true", help="also store tf.lite 2.17 reference outputs (needs TensorFlow)")
    ap.add_argument("--out-dir", type=Path, default=GOLDEN_DIR)
    ap.add_argument("--header", type=Path, default=FIRMWARE_DIR / "golden_set.h")
    args = ap.parse_args()

    cfg = load_config()
    classes = list(cfg["classes"])
    corpus = default_corpus_root(cfg)
    tables = build_tables(cfg, args.model)
    q = tables["quant"]
    scale, zp = q["input"]["scale"], q["input"]["zero_point"]
    from src.features import extract_mfcc

    clips = select_clips(list_test_clips(corpus, classes), classes, args.n, args.seed)
    it = litert(args.model)
    tf_it = None
    if args.with_tflite:
        import tensorflow as tf
        tf_it = tf.lite.Interpreter(model_path=str(args.model),
                                    experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_WITHOUT_DEFAULT_DELEGATES)
        tf_it.allocate_tensors()

    audio16, logmel, feat_ref, feat_rep, xq, prob, gap, prob_tf, labels, stems = [], [], [], [], [], [], [], [], [], []
    worst = 0.0
    for p, cls, idx in clips:
        a16, sr = sf.read(str(p), dtype="int16", always_2d=False)
        assert sr == tables["sample_rate"]
        a16 = np.pad(a16, (0, tables["clip_samples"] - len(a16)))[:tables["clip_samples"]]
        a32 = a16.astype(np.float32) / 32768.0
        ref = extract_mfcc(a32, cfg)
        lm, rep = features(a32, tables)
        worst = max(worst, float(np.abs(rep - ref).max()))
        x = quantize(ref, scale, zp)
        pr, gp = run_two(it, x)
        if tf_it is not None:
            tin = tf_it.get_input_details()[0]
            tf_it.set_tensor(tin["index"], x[np.newaxis, :, :, np.newaxis]); tf_it.invoke()
            touts = {int(o["shape"][-1]): tf_it.get_tensor(o["index"])[0].copy() for o in tf_it.get_output_details()}
            prob_tf.append(touts[15])
        audio16.append(a16); logmel.append(lm); feat_ref.append(ref); feat_rep.append(rep); xq.append(x)
        prob.append(pr); gap.append(gp if gp is not None else np.zeros(64, np.int8)); labels.append(idx); stems.append(p.stem)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    arrays = dict(audio_int16=np.stack(audio16), logmel=np.stack(logmel), features_librosa=np.stack(feat_ref),
                  features_frontend_ref=np.stack(feat_rep), input_int8=np.stack(xq), prob_int8=np.stack(prob),
                  gap_int8=np.stack(gap), labels=np.array(labels, np.int16), stems=np.array(stems),
                  classes=np.array(classes), input_scale=np.float32(scale), input_zero_point=np.int32(zp))
    if prob_tf:
        arrays["prob_int8_tflite217"] = np.stack(prob_tf)
    np.savez_compressed(args.out_dir / "golden_vectors.npz", **arrays)
    pred = np.stack(prob).argmax(axis=1)
    index = {
        "model": args.model.name, "n": len(clips), "seed": args.seed, "input_scale": scale, "input_zero_point": zp,
        "quant": {k: v for k, v in q.items() if k != "model"},
        "max_abs_diff_frontend_ref_vs_librosa": worst,
        "litert_argmax_accuracy_on_golden": float(np.mean(pred == np.array(labels))),
        "clips": [{"i": i, "stem": s, "class": classes[l], "label": int(l), "pred": int(pr)} for i, (s, l, pr) in enumerate(zip(stems, labels, pred))],
    }
    (args.out_dir / "golden_index.json").write_text(json.dumps(index, ensure_ascii=False, indent=1), encoding="utf-8")
    write_header(args.header, stems, labels, classes, audio16, xq, prob, np.stack(gap) if any(g is not None for g in gap) else None,
                 args.n_header_audio, args.n_header_feat)
    print(f"{len(clips)} clips from {len(set(c for _, c, _ in clips))} classes; max |frontend_ref − librosa| = {worst:.2e}; "
          f"LiteRT arg-max accuracy on golden = {index['litert_argmax_accuracy_on_golden']:.3f}")
    print(f"written {args.out_dir / 'golden_vectors.npz'} ({(args.out_dir / 'golden_vectors.npz').stat().st_size / 1e6:.1f} MB), "
          f"golden_index.json, {args.header} ({args.header.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
